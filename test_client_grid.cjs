const assert=require('node:assert/strict'),fs=require('node:fs');
const {ordered,move,save,read}=require('./static/client_grid.js');
const values=new Map(),storage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)};
const rows=[['Uno','A'],['Dos','B'],['Tres','C']];
assert.deepEqual(ordered(rows,'T1',storage),rows);
assert.equal(save('T1',['C','A','B'],storage),true);
assert.deepEqual(ordered(rows,'T1',storage).map(r=>r[1]),['C','A','B']);
assert.deepEqual(ordered(rows,'T2',storage),rows,'El orden no se comparte entre cuentas');
assert.deepEqual(ordered([...rows,['Nuevo','D']],'T1',storage).map(r=>r[1]),['C','A','B','D']);
assert.deepEqual(move(['A','B','C'],'A','C'),['B','C','A']);
assert.deepEqual(move(['A','B','C'],'C','A'),['C','A','B']);
assert.deepEqual(move(['A','B'],'missing','B'),['A','B']);
assert.deepEqual(rows,[['Uno','A'],['Dos','B'],['Tres','C']],'No cambia la matriz original');
assert.equal(save('T1',[],{setItem(){throw Error('Quota');}}),false);
assert.deepEqual(read('T1',{getItem:()=>'{invalid'}),[]);
const html=fs.readFileSync('templates/app_operativa_demo.html','utf8');
const reorder=html.slice(html.indexOf('  async function moveClient('),html.indexOf('  function openClient('));
assert.ok(!reorder.includes('operationsPost'),'El orden personal no modifica el orden global');
assert.ok(html.includes('HscClientGrid.attach'));
assert.ok(html.includes('id="startClientOrder"'));
const css=fs.readFileSync('static/client_grid.css','utf8'),js=fs.readFileSync('static/client_grid.js','utf8');
assert.ok(css.includes('@keyframes client-wiggle'));
assert.ok(css.includes('.client-order-actions:focus-within'));
assert.ok(js.includes('api.isEditing?.()'));
assert.ok(js.includes('api.onDone?.()'));
console.log('OK: orden personal, persistencia, usuarios aislados, nuevos clientes, movimiento y fallos de almacenamiento');
